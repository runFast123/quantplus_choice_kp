"""Writes supabase/seed/ref_signal_checks.sql (ADR-038): the research inputs the live RSI dip check needs.

  market_pit_top         each year's 300 most traded stocks, 2019-2026 (metalabel/out/pit_top300.csv)
  signal_check_models    the walk-forward model in force at each quarter start, 2024Q1-2026Q4, with that quarter's
                         hr_rule (metalabel/out/rsi_dip_tier_models_by_quarter.json, rsi_dip_hr_rule_by_quarter.csv)
  signal_check_training  every research RSI dip trade with its 25 features and result (rsi_dip_training_rows.csv)

Then it scores every stored signal once (svc_refresh_signal_checks(true)). Re-running the seed changes nothing.
Run from research/strategies/team:  python export_seed.py
"""
import json
import math
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
OUT = HERE / "metalabel" / "out"
SEED = HERE.parents[2] / "supabase" / "seed" / "ref_signal_checks.sql"
FEATURES = ["d200", "d50", "d20", "slope200", "rsi14", "rsi2", "atrpct", "volratio", "rs_rank", "r5", "r20", "r126",
            "dist_hi252", "clv", "gap", "sector_rank", "nifty_d200", "nifty_r20", "vix", "vix_chg5", "wx",
            "breadth50", "breadth200", "hr_rule", "n_same_day"]


def q(s):
    return "'" + str(s).replace("'", "''") + "'"


def num(x):
    return "null" if x is None or (isinstance(x, float) and math.isnan(x)) else repr(float(x))


def arr(xs):
    return "'{" + ",".join("NULL" if v is None or (isinstance(v, float) and math.isnan(v)) else repr(float(v))
                           for v in xs) + "}'"


def chunks(rows, n=500):
    for i in range(0, len(rows), n):
        yield rows[i:i + n]


pit = pd.read_csv(OUT / "pit_top300.csv")
hr = pd.read_csv(OUT / "rsi_dip_hr_rule_by_quarter.csv")
hr = {r.quarter_start: (None if pd.isna(r.hr_rule) else float(r.hr_rule)) for r in hr.itertuples()}
models = json.loads((OUT / "rsi_dip_tier_models_by_quarter.json").read_text(encoding="utf-8"))
train = pd.read_csv(OUT / "rsi_dip_training_rows.csv")
assert list(train.columns[3:]) == FEATURES, "training columns are not in FEATURES order"
assert all(m["features"] == FEATURES for m in models), "a model's features are not in FEATURES order"

lines = [
    "-- Reference data for the signal checks (ADR-038, migration 39). Generated by",
    "-- research/strategies/team/export_seed.py from the research team's files; do not edit by hand. Prod-safe.",
    f"-- {len(pit)} top-300 list rows, {len(models)} quarterly RSI dip models, {len(train)} research training trades.",
    "",
]
for part in chunks(list(pit.itertuples())):
    lines.append("insert into public.market_pit_top (year, symbol, exchange, rank) values")
    lines.append(",\n".join(f"  ({r.year}, {q(r.symbol)}, 'NSE', {r.rank})" for r in part))
    lines.append("on conflict (year, symbol, exchange) do nothing;")
lines.append("")
lines.append("insert into public.signal_check_models (strategy, valid_from, version, hr_rule, model) values")
lines.append(",\n".join(
    f"  ('rsi_dip', {q(m['valid_from'])}, {q(m['version'])}, {num(hr.get(m['valid_from']))}, {q(json.dumps(m))}::jsonb)"
    for m in models))
lines.append("on conflict (strategy, valid_from) do nothing;")
lines.append("")
for part in chunks(list(train.itertuples(index=False))):
    lines.append("insert into public.signal_check_training (strategy, symbol, signal_day, features, net, source) values")
    lines.append(",\n".join(
        f"  ('rsi_dip', {q(r.symbol)}, {q(r.signal_date)}, {arr(r[3:])}::float8[], {num(r.net)}, 'research')"
        for r in part))
    lines.append("on conflict (strategy, symbol, signal_day) do nothing;")
lines.append("")
lines.append("-- Score every stored signal once (frozen afterwards) and rebuild the market context.")
lines.append("select public.svc_refresh_signal_checks(true);")
SEED.write_text("\n".join(lines) + "\n", encoding="utf-8")
print("wrote", SEED, f"{SEED.stat().st_size / 1e6:.2f} MB")
