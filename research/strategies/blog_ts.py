"""Writes web/src/lib/blog/data.ts from data/blog_compare.json (made by compare_blog.py). Run after compare_blog.py:

    python compare_blog.py sma rsi kk strong && python compare_blog.py ma200 && python blog_ts.py
"""
import json
from pathlib import Path

HERE = Path(__file__).parent
d = json.load(open(HERE / "data" / "blog_compare.json", encoding="utf-8"))
KEEP = ("trades", "per_year", "made_money_pct", "avg_pct", "median_pct", "avg_win_pct", "avg_loss_pct", "worst10_pct",
        "best10_pct", "avg_days")


def side(b):
    return {"all": {k: b["all"][k] for k in KEEP}, "early": {k: b["2019_23"][k] for k in KEEP},
            "recent": {k: b["2024_26"][k] for k in KEEP}, "years": b["years"], "hist": [h["share_pct"] for h in b["hist"]]}


out = {"method": d["method"], "firstDay": d["first_day"], "lastDay": d["last_day"]}
for k in ("sma", "rsi", "kk", "strong", "ma200"):
    r = {"usual": side(d[k]["usual"]), "ours": side(d[k]["ours"]), "example": d[k]["example"]}
    if "usual_trail" in d[k]:
        r["usualTrail"] = side(d[k]["usual_trail"])
    out[k] = r

ts = f"""// GENERATED by research/strategies/blog_ts.py from data/blog_compare.json (compare_blog.py). Do not edit by hand.
// Each live rule next to the usual way of using the same indicator: same stocks (each year's 300 most traded NSE
// stocks), same years (July 2019 to October 2026), 0.5% round-trip cost, open trades left out. Tested on past prices.
import type {{ BlogData }} from "./types";

export const BLOG_DATA: BlogData = {json.dumps(out, separators=(",", ":"))};
"""
p = HERE.parent.parent / "web" / "src" / "lib" / "blog" / "data.ts"
p.parent.mkdir(parents=True, exist_ok=True)
p.write_text(ts, encoding="utf-8")
print("wrote", p, p.stat().st_size, "bytes")
